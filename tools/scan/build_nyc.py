"""THREADLINE — NYC official buildings for the scan map (seed MAN).

Replaces the scan's blobby buildings with the NYC Department of City Planning 3D model (2014), placed in the
scan's world frame through tools/scan/nyc_affine.json (found by registering the two height maps).

Geometry (see rebuild_walls): a building is its ROOF surfaces from the DCP model; every wall is regenerated by
hanging a vertical face from each roof boundary edge down to whatever is just outside that edge (a lower roof of
the same building, a neighbour's roof, or the ground). The DCP facade surfaces are only used for buildings that
have no roof. This makes every building closed and watertight by construction: no wall sheets sticking up past a
setback, no walls floating above a roof, no doubled / z-fighting walls, no party walls buried inside a
neighbour. Towers that the 2014 model does not have (newer buildings the scan shows) are added as extruded
prisms from the scan's own height map (scan_only_buildings), so no piece of the raw scan stands as a building.

Inputs : build/nyc_raw.pkl (tools/scan/nyc_extract.py), build/scan.json + scan.bin + scan_flat.npz
         (tools/scan/build_scan.py: frame, land mask, flattened scan for the colour bake), the scan texture.
Outputs: build/nyc.bin / nyc.json  buildings (flat triangles + per-vertex atlas UVs, per-building facade
                                   style/colour) + oriented box colliders fitted per building in its own orientation
         build/nyc_atlas.webp      the scan's colour baked per building (tools/scan/bake_nyc.py)
         build/nyc_mask.npz        0.5 m footprint id raster in the scan frame (build_scan.py uses it to cut
                                   the scan's buildings out and keep ground, trees, piers, the FDR)
         build/nyc_ground.jpg      street / sidewalk / park ground texture from the DCP linework
All paths honour TL_BUILD_DIR (via build_scan.OUT).
Usage  : python tools/scan/build_nyc.py
"""
